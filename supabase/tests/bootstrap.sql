-- STANDALONE TEST FIXTURE ONLY. This is not a replacement for Supabase Auth or
-- Realtime and must never be applied to a hosted Supabase project.
\set ON_ERROR_STOP on
do $$ begin
  if not exists(select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists(select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists(select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin bypassrls; end if;
end $$;
create schema auth;
create schema realtime;
create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb $$;
create function auth.uid() returns uuid language sql stable as $$ select nullif(auth.jwt() ->> 'sub', '')::uuid $$;
create function realtime.topic() returns text language sql stable as $$ select current_setting('realtime.topic', true) $$;
create table realtime.messages(id bigint generated by default as identity primary key, extension text not null);
alter table realtime.messages enable row level security;
grant usage on schema auth, realtime, public to anon, authenticated, service_role;
grant execute on function auth.jwt(), auth.uid(), realtime.topic() to anon, authenticated, service_role;
grant select, insert on realtime.messages to anon, authenticated;
grant usage on sequence realtime.messages_id_seq to anon, authenticated;
create function public.quiet_test_assert(condition boolean, message text) returns void language plpgsql as $$ begin if condition is distinct from true then raise exception 'Assertion failed: %', message; end if; end $$;
